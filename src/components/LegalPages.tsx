import { useEffect, useState } from 'react';
import { ChevronRight, FileText } from 'lucide-react';
import ClubLogo from './ClubLogo';

type Page = 'privacy' | 'terms';

function pageFromHash(): Page {
  return window.location.hash.includes('/legal/terms') ? 'terms' : 'privacy';
}

const S = ({ t, c }: { t: string; c: string }) => (
  <section className="space-y-1">
    <h3 className="text-yellow-500 font-bold text-sm">{t}</h3>
    <p className="text-zinc-300 text-xs leading-relaxed">{c}</p>
  </section>
);

export default function LegalPages() {
  const [page, setPage] = useState<Page>(pageFromHash);

  useEffect(() => {
    const onHash = () => setPage(pageFromHash());
    window.addEventListener('hashchange', onHash);
    return () => window.removeEventListener('hashchange', onHash);
  }, []);

  const go = (p: Page) => {
    window.location.hash = p === 'terms' ? '#/legal/terms' : '#/legal/privacy';
    setPage(p);
  };

  return (
    <div className="min-h-full bg-zinc-950 p-4 space-y-4" dir="rtl">
      <button onClick={() => { window.location.hash = '#/home'; }}
        className="flex items-center gap-2 text-yellow-500 text-sm font-bold">
        <ChevronRight size={16} /> العودة إلى التطبيق
      </button>

      <div className="flex items-center gap-3">
        <ClubLogo size={48} />
        <div>
          <h2 className="text-white font-black text-lg">الوثائق القانونية</h2>
          <p className="text-zinc-500 text-[11px]">نادي شباب أهلي برج بوعريريج (CABBA) — آخر تحديث : 2026-09-12</p>
        </div>
      </div>

      <div className="grid grid-cols-2 gap-2">
        <button onClick={() => go('privacy')}
          className={`p-3 rounded-xl border text-xs font-bold transition-colors ${page === 'privacy' ? 'bg-yellow-500 text-black border-yellow-500' : 'bg-zinc-900 text-zinc-300 border-zinc-800'}`}>
          سياسة الخصوصية
        </button>
        <button onClick={() => go('terms')}
          className={`p-3 rounded-xl border text-xs font-bold transition-colors ${page === 'terms' ? 'bg-yellow-500 text-black border-yellow-500' : 'bg-zinc-900 text-zinc-300 border-zinc-800'}`}>
          شروط الاستخدام
        </button>
      </div>

      {page === 'privacy' ? (
        <div className="bg-zinc-900 border border-zinc-800 rounded-2xl p-5 space-y-4">
          <S t="1. من نحن" c="منصة أنصار شباب أهلي برج بوعريريج (CABBA) يديرها النادي بمساعدة مقدم الخدمة التقني. لكل سؤال حول بياناتك : uncc.bba@gmail.com." />
          <S t="2. البيانات التي نجمعها" c="بيانات الحساب (الاسم المعروض، البريد الإلكتروني)، المحتويات التي تنشرها (منشورات، تعليقات، صور)، عمليات المتجر والانخراطات والتذاكر، سجلات مراقبة الأبواب (بوابة، وقت، مراقب)، وإحصائيات استخدام مجمعة." />
          <S t="3. لماذا نجمعها" c="لتشغيل خدمات النادي (أخبار، مباريات، متجر، تذاكر، انخراطات)، لتأمين المنصة ومنع الغش (تذكرة واحدة لكل دخول)، ولإعداد التقارير الشهرية للإدارة بصيغ مجمعة لا تكشف هويتك." />
          <S t="4. الأساس القانوني" c="موافقتك الصريحة عند إنشاء الحساب (المسجلة بتاريخها في سجلاتنا)، وتنفيذ العقد بينك وبين النادي (طلبك، تذكرتك، انخراطك)، وذلك طبقاً للقانون 18-07 المتعلق بحماية الأشخاص الطبيعيين في معالجة المعطيات ذات الطابع الشخصي." />
          <S t="5. الاستضافة والحفظ" c="تُحفظ البيانات في قاعدة بيانات سحابية مؤمّنة بنسخ احتياطية يومية؛ وتُحفظ سجلات المراقبة مدة اثني عشر (12) شهراً ثم تُحذف. حسابك يبقى قائماً حتى تطلب حذفه." />
          <S t="6. حقوقك" c="لك الحق في الاطلاع على بياناتك، تصحيحها، تصديرها (من ملفك الشخصي أو بطلب)، وحذفها نهائياً (يُستبدل اسمك بمعرف مجهول في السجلات التي يلزم القانون الاحتفاظ بها). تمارس حقوقك من التطبيق أو بالبريد أعلاه." />
          <S t="7. الإشعارات والتخزين المحلي" c="إشعارات الهاتف لا تُفعَّل إلا بموافقتك ويمكنك إلغاؤها من إعدادات المتصفح في أي وقت. التطبيق يخزّن جلستك وتفضيلاتك محلياً على جهازك فقط لتشغيل وضع عدم الاتصال." />
          <S t="8. الأمان" c="اتصالات مشفرة، كلمات مرور مجزأة، صلاحيات محدودة لكل دور، وسياسة أمن صارمة تمنع الحقن والتتبع. لا نبيع أي بيانات ولا نشاركها مع معلنين." />
          <S t="9. التغييرات" c="أي تعديل على هذه السياسة يُنشر في هذه الصفحة مع تاريخه، وتُعلَن التغييرات الجوهرية داخل التطبيق قبل سريانها." />
        </div>
      ) : (
        <div className="bg-zinc-900 border border-zinc-800 rounded-2xl p-5 space-y-4">
          <S t="1. الغرض من المنصة" c="قناة رسمية رقمية للنادي : الأخبار، المباريات، المشاركة (توقعات، استطلاعات، أفضل لاعب)، المجتمع، المتجر، الانخراطات، التذاكر وصندوق الدعم." />
          <S t="2. الحساب" c="حساب واحد لكل شخص بمعلومات صحيحة. أنت مسؤول عن سرية كلمة مرورك وعن كل نشاط يجري بحسابك. الحسابات الآلية أو المنتحلة تُعلَّق." />
          <S t="3. سلوك المجتمع" c="يُمنع السب، التحريض، انتحال صفة النادي أو لاعبيه، نشر صور الآخرين دون حق، وأي محتوى مخالف للقانون الجزائري. للنادي حق الحذف والتعليق دون إنذار في الحالات الواضحة." />
          <S t="4. التذاكر والأبواب" c="كل رمز تذكرة صالح لدخول واحد وغير قابل للتحويل. لقطة الشاشة الممسوحة ثانية تُرفض تلقائياً. سجلات المرور دليل النادي عند أي نزاع." />
          <S t="5. المتجر والانخراطات" c="الأسعار بالدينار الجزائري، المخزون محدود، وحالة كل طلب تُبلَّغ بالبريد. بطاقة الانخراط شخصية ورمزها مرتبط بحسابك." />
          <S t="6. الملكية الفكرية" c="شعار النادي ومحتوياته الرسمية ملك للنادي. الكود المصدري ملك لمقدم الخدمة طيلة مدة العقد وفق الاتفاق المبرم مع النادي." />
          <S t="7. المسؤولية" c="لا تتحمل المنصة مسؤولية انقطاع خارج عن إرادتها (كهرباء، شبكات)، ولا فروق بيانات المباريات الواردة من المصادر الرسمية قبل تصحيحها." />
          <S t="8. القانون المطبق" c="القانون الجزائري؛ الاختصاص القضائي لمحاكم برج بوعريريج بعد محاولة تسوية ودية." />
          <S t="9. التعديلات" c="يجوز للنادي تحديث هذه الشروط؛ يسري التحديث بنشره هنا، واستمرارك في الاستخدام بعده قبول به." />
        </div>
      )}

      <p className="text-[10px] text-zinc-600 flex items-center gap-1">
        <FileText size={12} /> وثيقتان تُعرضان قبل إنشاء الحساب وبعده، ومضمّنتان في كل بريد ترسله المنصة.
      </p>
    </div>
  );
}
